// Generates supabase/seed.sql from the site's current static content, so the
// database starts out identical to what content.js / app.js / index.html show today.
//
//   node supabase/scripts/gen-seed.mjs
//
// Every insert uses ON CONFLICT DO NOTHING: re-running the seed never overwrites
// edits made in the admin panel.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const read = f => fs.readFileSync(path.join(ROOT, f), 'utf8');

// content.js → DEFAULT_CONTENT
const ctx = { window: {} };
vm.runInNewContext(read('content.js'), ctx);
const DEF = ctx.window.DEFAULT_CONTENT;

// app.js → the T (UI strings) dictionary, for services and SEO texts
const app = read('app.js');
const tStart = app.indexOf('var T={');
const tEnd = app.indexOf('\n  };', tStart);
if (tStart < 0 || tEnd < 0) throw new Error('T dictionary not found in app.js');
const T = vm.runInNewContext('(' + app.slice(tStart + 'var T='.length, tEnd + 4).trim().replace(/;$/, '') + ')');
const both = key => ({ tr: T.tr[key], en: T.en[key] });

// index.html → services rows (title/desc keys + tags, some of which are translated)
const html = read('index.html');
const services = [...html.matchAll(/<div class="svc-row[^"]*">([\s\S]*?)<\/div><\/div><\/div>/g)].map(m => {
  const row = m[1];
  const key = row.match(/class="svc-t" data-i18n="(sv\d+)"/)[1];
  const tags = [...row.match(/<div class="svc-tags">([\s\S]*)$/)[1].matchAll(/<span(?: data-i18n="([a-z_]+)")?>([^<]*)<\/span>/g)]
    .map(([, k, text]) => (k ? both(k) : { tr: text, en: text }));
  return { title: both(key), desc: both(key + 'd'), tags };
});
if (services.length !== 9) throw new Error('expected 9 services, found ' + services.length);

// media/ → builtin library rows (with WebP dimensions)
function webpSize(buf) {
  const chunk = buf.toString('ascii', 12, 16);
  if (chunk === 'VP8 ') return [buf.readUInt16LE(26) & 0x3fff, buf.readUInt16LE(28) & 0x3fff];
  if (chunk === 'VP8L') { const b = buf.readUInt32LE(21); return [(b & 0x3fff) + 1, ((b >> 14) & 0x3fff) + 1]; }
  if (chunk === 'VP8X') return [buf.readUIntLE(24, 3) + 1, buf.readUIntLE(27, 3) + 1];
  return [0, 0];
}
const builtin = fs.readdirSync(path.join(ROOT, 'media')).filter(f => /\.(webp|png|jpe?g|gif)$/i.test(f)).sort().map(f => {
  const buf = fs.readFileSync(path.join(ROOT, 'media', f));
  const [w, h] = /\.webp$/i.test(f) ? webpSize(buf) : [0, 0];
  return { path: 'media/' + f, mime: /\.webp$/i.test(f) ? 'image/webp' : 'image/' + f.split('.').pop().toLowerCase(), size: buf.length, w, h };
});

// ---------------------------------------------------------------- SQL
const lit = s => "'" + String(s).replace(/'/g, "''") + "'";
const json = v => lit(JSON.stringify(v)) + '::jsonb';
const arr = a => 'array[' + a.map(lit).join(',') + ']::text[]';
const st = DEF.settings;
const out = [];
out.push('-- GENERATED by supabase/scripts/gen-seed.mjs from content.js, app.js and index.html. Do not edit by hand.');
out.push('-- Safe to re-run: existing rows (edited in the panel) are never overwritten.\n');

out.push(`insert into public.settings (id, status, available_from, email, linkedin, socials, form_access_key, admin_theme, default_project_theme)
values (1, ${lit(st.status)}, ${json(st.availableFrom || { tr: '', en: '' })}, ${lit(st.email)}, ${lit(st.linkedin)}, '{}'::jsonb, ${lit(st.formAccessKey || '')}, 'system', 'cobalt')
on conflict (id) do nothing;\n`);

const sections = {
  hero: { lede: DEF.texts.hero_lede },
  about: { statement: DEF.texts.statement, more: DEF.texts.about_more },
  services: { items: services },
  contact: { lede: DEF.texts.c_lede },
  seo: { title: both('_title'), description: both('_desc') },
  testimonials: { items: DEF.testimonials || [] }
};
out.push('insert into public.content_sections (key, data) values');
out.push(Object.entries(sections).map(([k, v]) => `  (${lit(k)}, ${json(v)})`).join(',\n'));
out.push('on conflict (key) do nothing;\n');

out.push('insert into public.projects (id, sort_order, visible, featured, badge, theme, mock, name, cat, description, tags, facts, tech, media) values');
out.push(DEF.projects.map((p, i) => `  (${lit(p.id)}, ${(i + 1) * 10}, ${p.visible !== false}, ${p.featured !== false}, ${lit(p.badge || '')}, ${lit(p.theme || 'cobalt')}, ${lit(p.mock || '')},
   ${json(p.name)}, ${json(p.cat)}, ${json(p.desc)}, ${json(p.tags || { tr: [], en: [] })}, ${json(p.facts || [])}, ${arr(p.tech || [])}, ${json(p.media || [])})`).join(',\n'));
out.push('on conflict (id) do nothing;\n');

out.push('insert into public.media (kind, path, url, mime, size_bytes, width, height) values');
out.push(builtin.map(m => `  ('builtin', ${lit(m.path)}, ${lit(m.path)}, ${lit(m.mime)}, ${m.size}, ${m.w}, ${m.h})`).join(',\n'));
out.push('on conflict (path) do nothing;');

fs.writeFileSync(path.join(ROOT, 'supabase/seed.sql'), out.join('\n') + '\n');

// The admin panel's demo mode (no Supabase configured) starts from the very same rows.
const now = new Date().toISOString();
const demo = {
  settings: { id: 1, status: st.status, available_from: st.availableFrom || { tr: '', en: '' }, email: st.email, linkedin: st.linkedin, socials: {},
    form_access_key: st.formAccessKey || '', admin_theme: 'system', default_project_theme: 'cobalt', updated_at: now },
  content_sections: Object.entries(sections).map(([key, data]) => ({ key, data, updated_at: now })),
  projects: DEF.projects.map((p, i) => ({ id: p.id, sort_order: (i + 1) * 10, visible: p.visible !== false, featured: p.featured !== false, badge: p.badge || '',
    theme: p.theme || 'cobalt', mock: p.mock || '', name: p.name, cat: p.cat, description: p.desc, tags: p.tags || { tr: [], en: [] }, facts: p.facts || [],
    tech: p.tech || [], media: p.media || [], created_at: now, updated_at: now })),
  media: builtin.map((m, i) => ({ id: 'builtin-' + (i + 1), kind: 'builtin', path: m.path, url: m.path, mime: m.mime, size_bytes: m.size, width: m.w, height: m.h, alt: '', created_at: now })),
  messages: []
};
fs.writeFileSync(path.join(ROOT, 'admin/js/services/adapters/demo-seed.json'), JSON.stringify(demo) + '\n');
console.log(`seed.sql + demo-seed.json: ${DEF.projects.length} projects, ${services.length} services, ${builtin.length} builtin media`);
