// Minimal DOM helpers. Text always goes through textContent; there is no innerHTML path for data.

/**
 * h('button', { class: 'btn', onclick: fn, 'aria-label': 'Kapat' }, 'text', childNode)
 * Special attrs: class, text, dataset {}, style {}, on* (listeners), value/checked/disabled/hidden (props).
 */
export function h(tag, attrs, ...children) {
  const el = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs || {})) {
    if (v == null || v === false) continue;
    if (k === 'class') el.className = v;
    else if (k === 'text') el.textContent = v;
    else if (k === 'dataset') Object.assign(el.dataset, v);
    else if (k === 'style') Object.assign(el.style, v);
    else if (k.startsWith('on') && typeof v === 'function') el.addEventListener(k.slice(2), v);
    else if (k in PROPS) el[k] = v;
    else el.setAttribute(k, v === true ? '' : v);
  }
  append(el, children);
  return el;
}
const PROPS = { value: 1, checked: 1, disabled: 1, hidden: 1, selected: 1, htmlFor: 1, multiple: 1, required: 1, readOnly: 1 };

export function append(el, children) {
  for (const c of children.flat(Infinity)) {
    if (c == null || c === false) continue;
    el.append(c instanceof Node ? c : document.createTextNode(String(c)));
  }
  return el;
}

/** Replaces all children of `el`. */
export function mount(el, ...children) { el.replaceChildren(); return append(el, children); }

